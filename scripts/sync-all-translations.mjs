/**
 * Syncs i18n locale files and Supabase seed JSON from en.ts + per-language overrides.
 * Run: node scripts/sync-all-translations.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const localesDir = path.join(root, 'i18n', 'locales');
const seedDir = path.join(root, 'supabase', 'seed', 'translations');

const ALL_LANGS = [
  'en', 'zh', 'hi', 'es', 'fr', 'ar', 'bn', 'pt', 'ru', 'ur',
  'id', 'de', 'ja', 'sw', 'mr', 'te', 'tr', 'ta', 'vi', 'ko',
  'it', 'th', 'gu', 'pl', 'uk', 'ml', 'kn', 'pa', 'nl', 'ro',
];

function parseLocaleFile(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  if (raw.includes('.data.json')) {
    const jsonPath = filePath.replace('.ts', '.data.json');
    if (fs.existsSync(jsonPath)) {
      return JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    }
  }
  const eq = raw.indexOf('=');
  const start = raw.indexOf('{', eq);
  const end = raw.lastIndexOf('};');
  if (start === -1 || end === -1) throw new Error(`Could not parse: ${filePath}`);
  return new Function(`return (${raw.slice(start, end + 1)})`)();
}

function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) flatten(v, key, out);
    else out[key] = v;
  }
  return out;
}

function unflatten(flat) {
  const out = {};
  for (const [key, val] of Object.entries(flat)) {
    const parts = key.split('.');
    let cur = out;
    for (let i = 0; i < parts.length - 1; i++) {
      cur[parts[i]] = cur[parts[i]] ?? {};
      cur = cur[parts[i]];
    }
    cur[parts[parts.length - 1]] = val;
  }
  return out;
}

async function translateSingle(text, targetLang) {
  if (!text || typeof text !== 'string' || !/[a-zA-Z]/.test(text)) return text;
  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`;
    const res = await fetch(url);
    const data = await res.json();
    let tr = '';
    if (Array.isArray(data) && Array.isArray(data[0])) {
      for (const p of data[0]) if (Array.isArray(p) && typeof p[0] === 'string') tr += p[0];
    }
    return tr || text;
  } catch {
    return text;
  }
}

async function translateBatch(texts, targetLang) {
  if (targetLang === 'en') return texts;
  const chunkSize = 15;
  const results = new Array(texts.length);
  for (let i = 0; i < texts.length; i += chunkSize) {
    const chunk = texts.slice(i, i + chunkSize);
    const chunkRes = await Promise.all(chunk.map(async (item) => {
      if (Array.isArray(item)) {
        return Promise.all(item.map((sub) => translateSingle(sub, targetLang)));
      }
      return translateSingle(item, targetLang);
    }));
    for (let j = 0; j < chunkRes.length; j++) {
      results[i + j] = chunkRes[j];
    }
  }
  return results;
}

async function buildLang(enFlat, lang) {
  if (lang === 'en') return enFlat;
  const localePath = path.join(localesDir, `${lang}.ts`);
  if (fs.existsSync(localePath)) {
    const existing = flatten(parseLocaleFile(localePath));
    const merged = { ...enFlat };
    for (const [k, v] of Object.entries(existing)) {
      if (v !== undefined && v !== enFlat[k]) merged[k] = v;
    }
    const missing = Object.keys(enFlat).filter((k) => {
      if (Array.isArray(enFlat[k])) {
        return !Array.isArray(merged[k]) || merged[k].length === 0 || merged[k][0] === enFlat[k][0];
      }
      return merged[k] === enFlat[k] || merged[k] === undefined;
    });
    if (missing.length === 0) return merged;
    const translated = await translateBatch(missing.map((k) => enFlat[k]), lang);
    missing.forEach((k, i) => {
      merged[k] = translated[i];
    });
    return merged;
  }
  const keys = Object.keys(enFlat);
  const translated = await translateBatch(keys.map((k) => enFlat[k]), lang);
  const out = {};
  keys.forEach((k, i) => {
    out[k] = translated[i];
  });
  return out;
}

function sqlEscapeJson(obj) {
  return JSON.stringify(obj).replace(/'/g, "''");
}

function writeLocaleTs(lang, data) {
  if (lang === 'en') return;
  const importLine = "import type { Translations } from './en';\n\n";
  const body = JSON.stringify(data, null, 2);
  const content =
    `${importLine}const ${lang}: Translations = ${body};\n\nexport default ${lang};\n`;
  fs.writeFileSync(path.join(localesDir, `${lang}.ts`), content);
}

const enData = parseLocaleFile(path.join(localesDir, 'en.ts'));
const enFlat = flatten(enData);

fs.mkdirSync(seedDir, { recursive: true });

const sqlStatements = [
  '-- Auto-generated by scripts/sync-all-translations.mjs',
  '-- Populates strings for all 30 app_languages rows.',
  '',
];

for (const lang of ALL_LANGS) {
  console.log(`Building ${lang}...`);
  const flat = await buildLang(enFlat, lang);
  const data = unflatten(flat);
  fs.writeFileSync(path.join(seedDir, `${lang}.json`), JSON.stringify(data, null, 2));
  if (lang === 'es' || lang === 'fr' || lang === 'pl') writeLocaleTs(lang, data);
  sqlStatements.push(
    `update public.app_languages\n` +
      `set strings = '${sqlEscapeJson(data)}'::jsonb,\n` +
      `    updated_at = timezone('utc', now())\n` +
      `where code = '${lang}';`,
    ''
  );
}

const migrationPath = path.join(root, 'supabase', 'migrations', '20260615120000_sync_all_translations.sql');
fs.writeFileSync(migrationPath, sqlStatements.join('\n'));
console.log(`Wrote ${ALL_LANGS.length} JSON files, es/fr/pl TS, and ${migrationPath}`);
